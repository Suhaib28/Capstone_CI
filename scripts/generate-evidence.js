const { spawnSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");

function run(command, args) {
  return spawnSync(command, args, {
    encoding: "utf8",
    shell: process.platform === "win32"
  });
}

const testRun = run("node", ["--test"]);
const check1 = run("node", ["--check", "src/sessionPolicy.js"]);
const check2 = run("node", ["--check", "test/sessionPolicy.test.js"]);

const passed = testRun.status === 0 && check1.status === 0 && check2.status === 0;
const stamp = new Date().toISOString();

const esc = (s) => String(s ?? "")
  .replaceAll("&", "&amp;")
  .replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;");

const output = `${testRun.stdout || ""}${testRun.stderr || ""}`.trim();

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Sport Sitters CI Competency Evidence</title>
<style>
body{font-family:Arial,sans-serif;margin:40px;max-width:1000px;color:#17202a}
h1{margin-bottom:4px}.status{font-size:24px;font-weight:700}
.card{border:1px solid #bbb;border-radius:10px;padding:18px;margin:16px 0}
pre{background:#111;color:#f5f5f5;padding:18px;border-radius:8px;overflow:auto;font-size:14px}
code{font-family:Consolas,monospace}
table{border-collapse:collapse;width:100%}td,th{border:1px solid #ccc;padding:8px;text-align:left}
</style>
</head>
<body>
<h1>Sport Sitters CI Competency Evidence</h1>
<p>This report was generated by actually executing syntax checks and the automated test suite on this machine.</p>
<div class="card">
  <div class="status">${passed ? "PASS — Verification completed successfully" : "FAIL — Verification found a problem"}</div>
  <table>
    <tr><th>Generated</th><td>${esc(stamp)}</td></tr>
    <tr><th>Node.js</th><td>${esc(process.version)}</td></tr>
    <tr><th>Platform</th><td>${esc(process.platform)} ${esc(process.arch)}</td></tr>
    <tr><th>Host</th><td>${esc(os.hostname())}</td></tr>
    <tr><th>Syntax check: source</th><td>${check1.status === 0 ? "PASS" : "FAIL"}</td></tr>
    <tr><th>Syntax check: tests</th><td>${check2.status === 0 ? "PASS" : "FAIL"}</td></tr>
    <tr><th>Automated test suite</th><td>${testRun.status === 0 ? "PASS" : "FAIL"}</td></tr>
  </table>
</div>
<div class="card">
<h2>Actual Test Output</h2>
<pre>${esc(output)}</pre>
</div>
<div class="card">
<h2>What this demonstrates</h2>
<p>The project validates a Sport Sitters-inspired booking-chat session policy. The same syntax and automated test commands are also configured in <code>.github/workflows/ci.yml</code>, allowing GitHub Actions to execute the checks automatically on pushes and pull requests.</p>
</div>
</body>
</html>`;

fs.mkdirSync("evidence", { recursive: true });
fs.writeFileSync(path.join("evidence", "ci-evidence.html"), html);
fs.writeFileSync(path.join("evidence", "test-output.txt"), output + "\n");
fs.writeFileSync(path.join("evidence", "verification.json"), JSON.stringify({
  generatedAt: stamp,
  node: process.version,
  platform: process.platform,
  arch: process.arch,
  syntaxSourcePassed: check1.status === 0,
  syntaxTestsPassed: check2.status === 0,
  testsPassed: testRun.status === 0
}, null, 2) + "\n");

console.log("");
console.log("====================================================");
console.log(" SPORT SITTERS COMPETENCY EVIDENCE");
console.log("====================================================");
console.log(`Syntax check: ${check1.status === 0 && check2.status === 0 ? "PASS" : "FAIL"}`);
console.log(`Automated tests: ${testRun.status === 0 ? "PASS" : "FAIL"}`);
console.log(`Evidence report: ${path.resolve("evidence", "ci-evidence.html")}`);
console.log("Open that HTML file and take a screenshot for your report.");
console.log("====================================================");

process.exit(passed ? 0 : 1);
